#!/bin/bash
# Usage: sync-theme.sh SCHEME MODE
# Mirrors the kitty SCHEME-{dark,light}.conf palettes into foot:
#   1. theme.ini   included by foot.ini (new foot processes: both modes, active one first)
#   2. theme.osc   escape sequences for the active mode, replayed by theme-env.sh
#                  so new windows of a long-running `foot --server` catch up
#   3. live push   same sequences written to every pty owned by a running foot
# Called from sync-terminal-theme.sh. Kitty files stay the single source of truth.
set -euo pipefail

SCHEME="${1:?scheme}" MODE="${2:?mode}"
KITTY_DIR="${KITTY_DIR:-$HOME/.config/kitty}"
FOOT_DIR="${FOOT_DIR:-$HOME/.config/foot}"
NO_PUSH="${NO_PUSH:-0}"

# Prints the foot [colors-$1] body for kitty file $2.
foot_colors() {
  awk -v sec="$1" '
    function hex(v) { sub(/^#/, "", v); return tolower(v) }
    $1 == "foreground"           { fg = hex($2) }
    $1 == "background"           { bg = hex($2) }
    $1 == "selection_foreground" { sfg = hex($2) }
    $1 == "selection_background" { sbg = hex($2) }
    $1 == "cursor"               { cur = hex($2) }
    $1 == "cursor_text_color"    { curtext = hex($2) }
    $1 == "url_color"            { url = hex($2) }
    $1 ~ /^color([0-9]|1[0-5])$/ { n = substr($1, 6); c[n] = hex($2) }
    END {
      printf "[colors-%s]\n", sec
      printf "foreground=%s\nbackground=%s\n", fg, bg
      if (sfg != "" && sbg != "") printf "selection-foreground=%s\nselection-background=%s\n", sfg, sbg
      if (cur != "") printf "cursor=%s %s\n", (curtext != "" ? curtext : bg), cur
      if (url != "") printf "urls=%s\n", url
      for (i = 0; i < 8; i++)  printf "regular%d=%s\n", i, c[i]
      for (i = 8; i < 16; i++) printf "bright%d=%s\n", i - 8, c[i]
    }' "$2"
}

# Prints OSC 4/10/11/12/17/19 for kitty file $1.
osc_sequences() {
  awk '
    function hex(v) { sub(/^#/, "", v); return "#" tolower(v) }
    function osc(s) { printf "\033]%s\033\\", s }
    $1 == "foreground"           { fg = hex($2) }
    $1 == "background"           { bg = hex($2) }
    $1 == "selection_foreground" { sfg = hex($2) }
    $1 == "selection_background" { sbg = hex($2) }
    $1 == "cursor"               { cur = hex($2) }
    $1 ~ /^color([0-9]|1[0-5])$/ { n = substr($1, 6); c[n] = hex($2) }
    END {
      for (i = 0; i < 16; i++) osc("4;" i ";" c[i])
      osc("10;" fg); osc("11;" bg)
      if (cur != "") osc("12;" cur)
      if (sbg != "") osc("17;" sbg)
      if (sfg != "") osc("19;" sfg)
    }' "$1"
}

kitty_file() { echo "$KITTY_DIR/$SCHEME-$1.conf"; }
for m in dark light; do
  [ -f "$(kitty_file "$m")" ] || { echo "missing $(kitty_file "$m")" >&2; exit 1; }
done

mkdir -p "$FOOT_DIR"
tmp="$FOOT_DIR/theme.ini.tmp.$$"
{
  echo "# Generated by sync-theme.sh from kitty $SCHEME-{dark,light}.conf. Do not edit."
  echo "[main]"
  echo "initial-color-theme=$MODE"
  echo
  foot_colors dark "$(kitty_file dark)"
  echo
  foot_colors light "$(kitty_file light)"
} >"$tmp"
mv -f "$tmp" "$FOOT_DIR/theme.ini"

osc_sequences "$(kitty_file "$MODE")" >"$FOOT_DIR/theme.osc.tmp.$$"
mv -f "$FOOT_DIR/theme.osc.tmp.$$" "$FOOT_DIR/theme.osc"

[ "$NO_PUSH" = 1 ] && exit 0
for pid in $(pgrep -x 'foot|footclient' || true); do
  for tty in $(ps -o tty= --ppid "$pid" 2>/dev/null | sort -u); do
    [ "$tty" = "?" ] && continue
    cat "$FOOT_DIR/theme.osc" >"/dev/$tty" 2>/dev/null || true
  done
done
