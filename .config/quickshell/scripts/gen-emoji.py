#!/usr/bin/env python3
"""Generate config/launcher/EmojiData.js from Unicode names and the installed
Noto Color Emoji coverage. Deterministic: same font + same Python unicodedata
gives the same file. Single code points only (no ZWJ sequences or skin tones).

Run: python3 scripts/gen-emoji.py [--check]   (--check exits 1 if the file is stale)
"""
import json, subprocess, sys, unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "config" / "launcher" / "EmojiData.js"
FONT = "/usr/share/fonts/noto/NotoColorEmoji.ttf"

BMP_EMOJI = {0x203C, 0x2049, 0x2122, 0x2139, 0x231A, 0x231B, 0x24C2, 0x25AA, 0x25AB, 0x25B6, 0x25C0,
             0x2B05, 0x2B06, 0x2B07, 0x2B1B, 0x2B1C, 0x2B50, 0x2B55, 0x2934, 0x2935, 0x3030, 0x303D,
             0x3297, 0x3299, *range(0x2194, 0x219A), 0x21A9, 0x21AA, *range(0x23E9, 0x23F4),
             *range(0x23F8, 0x23FB), *range(0x25FB, 0x25FF)}


# Unicode character names that differ from the names people search for.
RENAMES = {
    0x2764: "red heart", 0x263A: "smiling face", 0x2639: "frowning face", 0x2705: "check mark button",
    0x2714: "check mark", 0x2716: "multiply", 0x2B50: "star", 0x2600: "sun", 0x2601: "cloud",
    0x2602: "umbrella", 0x2603: "snowman", 0x2604: "comet", 0x260E: "telephone", 0x2611: "check box",
    0x2618: "shamrock", 0x261D: "index pointing up", 0x2620: "skull and crossbones", 0x2622: "radioactive",
    0x2623: "biohazard", 0x262E: "peace symbol", 0x2648: "aries", 0x2665: "heart suit", 0x2660: "spade suit",
    0x2663: "club suit", 0x2666: "diamond suit", 0x267B: "recycling symbol", 0x26A0: "warning",
    0x26A1: "high voltage", 0x2728: "sparkles", 0x2744: "snowflake", 0x2757: "exclamation mark",
    0x2753: "question mark", 0x1F44D: "thumbs up", 0x1F44E: "thumbs down", 0x1F44B: "waving hand",
    0x1F44F: "clapping hands", 0x1F64F: "folded hands", 0x1F4A9: "pile of poo",
}


def font_codepoints():
    out = subprocess.run(["fc-query", "--format=%{charset}", FONT], capture_output=True, text=True, check=True).stdout
    cps = set()
    for part in out.split():
        lo, _, hi = part.partition("-")
        cps.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return cps


def wanted(cp):
    return cp in BMP_EMOJI or 0x2600 <= cp <= 0x27BF or 0x1F300 <= cp <= 0x1FAFF


def main():
    have = font_codepoints()
    rows = []
    for cp in sorted(c for c in have if wanted(c)):
        name = unicodedata.name(chr(cp), "")
        # Regional indicators, skin-tone modifiers and tag characters are not standalone emoji.
        if not name or name.startswith(("REGIONAL INDICATOR", "EMOJI MODIFIER", "TAG ", "VARIATION")):
            continue
        rows.append([chr(cp), RENAMES.get(cp, name.lower())])
    body = ".pragma library\n\n// Generated by scripts/gen-emoji.py. Do not edit.\n// [character, lowercase Unicode name]\nvar EMOJI = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")).replace("],[", "],\n[") + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == body else 1)
    OUT.write_text(body)
    print(f"wrote {OUT} ({len(rows)} emoji)")


main()
