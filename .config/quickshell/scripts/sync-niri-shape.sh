#!/usr/bin/env bash
# Writes $NIRI_CONFIG_DIR/style.kdl (default ~/.config/niri/style.kdl):
# square window corners under the dwm style, no overrides otherwise.
# Niri includes it last in config.kdl, so its window-rule wins over the
# radius-16 rules in windowrules.kdl and colors.kdl.
set -euo pipefail

style="${1:-}"
dir="${NIRI_CONFIG_DIR:-$HOME/.config/niri}"
out="$dir/style.kdl"

if [[ "$style" == "dwm" ]]; then
  body='// Generated by sync-niri-shape.sh: dwm style squares window corners.
window-rule {
    geometry-corner-radius 0
    clip-to-geometry true
}'
else
  body='// Generated by sync-niri-shape.sh: no overrides for this style.'
fi

mkdir -p "$dir"
# Rewrite only on change so Niri does not reload its config needlessly.
if [[ ! -f "$out" || "$(cat "$out")" != "$body" ]]; then
  printf '%s\n' "$body" > "$out.tmp"
  mv "$out.tmp" "$out"
fi
