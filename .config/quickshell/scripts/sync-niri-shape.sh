#!/usr/bin/env bash
# Clears the obsolete style-specific override in $NIRI_CONFIG_DIR/style.kdl.
# Niri keeps its normal window rules and palette-generated decorations.
set -euo pipefail

dir="${NIRI_CONFIG_DIR:-$HOME/.config/niri}"
out="$dir/style.kdl"

body='// Generated by sync-niri-shape.sh: no shell-specific shape overrides.'

mkdir -p "$dir"
# Rewrite only on change so Niri does not reload its config needlessly.
if [[ ! -f "$out" || "$(cat "$out")" != "$body" ]]; then
  printf '%s\n' "$body" > "$out.tmp"
  mv "$out.tmp" "$out"
fi
