// Gate test: node tests/sidebar/wiring.test.mjs (structural)
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import assert from "node:assert/strict"
const rd = p => readFileSync(fileURLToPath(new URL(p, import.meta.url)), "utf8")

const svc = rd("../../config/SystemMetricsService.qml")
assert.match(svc, /pragma Singleton/)
assert.match(svc, /import "SystemMetrics\.js" as SystemMetrics/)
assert.match(svc, /running: root\.active/, "polls only while active")
for (const p of ["/proc/stat", "/proc/meminfo", "/proc/net/dev", "/proc/uptime", "/sys/class/thermal"])
  assert.ok(svc.includes(p), p)
const qmldir = rd("../../config/qmldir")
assert.match(qmldir, /singleton SystemMetricsService 1\.0 SystemMetricsService\.qml/)

const media = rd("../../config/MediaService.qml")
for (const f of ["positionSec", "function seekBy(", "function seekTo(", "function stop(", "function playerVolumeBy("])
  assert.ok(media.includes(f), f)
const ctl = rd("../../scripts/mpris_control.py")
for (const a of ["'seek'", "'position'", "'volume'"]) assert.ok(ctl.includes(a), a)
assert.match(rd("../../scripts/mpris_monitor.py"), /position_sec/)

const fonts = rd("../../config/BottomBarFonts.qml")
assert.match(fonts, /clockFamily/)
assert.match(fonts, /clockMinutesFamily/)
assert.match(fonts, /Baro Plain/)
assert.match(fonts, /Baro LineThree/)

const settings = rd("../../config/Settings.qml")
assert.match(settings, /sidebarEdgeHover: true/)
assert.match(settings, /property alias sidebarEdgeHover: adapter\.sidebarEdgeHover/)
assert.match(rd("../../bar/settings/AppearanceTab.qml"), /sidebarEdgeHover/)
assert.match(settings, /property bool sidebarEdgeHover: root\.defaults\.sidebarEdgeHover/)
assert.match(settings, /sidebarEdgeHover = root\.defaults\.sidebarEdgeHover/)
// Search entry anchor must equal a row label in AppearanceTab so it scrolls and highlights.
const panel = rd("../../bar/SettingsPanel.qml")
const entry = panel.match(/title: "Sidebar edge hover", anchor: "([^"]+)"/)
assert.ok(entry, "search entry needs an anchor")
assert.ok(rd("../../bar/settings/AppearanceTab.qml").includes(`title: "${entry[1]}"`), "anchor matches row title")

assert.match(svc, /interval: 2000[\s\S]*?running: root\.active\b(?! \|\|)/)
assert.doesNotMatch(svc, /\|\| true/)
assert.equal((svc.match(/path: root\.active \? "/g) || []).length, 5, "all five FileView paths gated")
assert.equal((svc.match(/onLoadFailed/g) || []).length, 5)
assert.match(svc, /onActiveChanged:[\s\S]*prevCpu = null/)
assert.match(media, /positionSec = info\.position_sec/)
const mon = rd("../../scripts/mpris_monitor.py")
assert.match(mon, /'position_sec': 0/)
assert.match(mon, /signal_name='Seeked'/)
assert.match(mon, /GLib\.timeout_add_seconds\(1,/)
assert.match(fonts, /textFamily: pick\("Kyok medium"\)/)
console.log("sidebar wiring (services): ok")

// Task 4: the window, the edge activator and the shell wiring.
const side = rd("../../bar/Sidebar.qml")
assert.match(side, /anchors\.top: false/)
assert.match(side, /anchors\.bottom: true/)
assert.match(side, /margins\.bottom: Config\.bottomBarHeight \+ Config\.dp\(7\)/)
assert.match(side, /surfaceWidth: Config\.dp\(300\)/)
assert.match(side, /readonly property int pageCount: content\.pageCount/)
assert.match(side, /acceptedButtons: Qt\.MiddleButton/)
assert.match(side, /property: "topLeftRadius"; value: 0/)
assert.match(side, /property: "bottomLeftRadius"; value: 0/)
assert.match(side, /property: "bottomRightRadius"; value: Config\.dp\(20\)/)
assert.match(side, /surfaceHeight: Math\.min\(Config\.dp\(554\) \+ Config\.dp\(106\),\s*root\.screenH - Config\.bottomBarHeight - Config\.dp\(7\) - Config\.barWidth\)/)
assert.match(side, /surfaceColor: Colors\.surface$/m)
assert.match(side, /onEscaped: root\.dismissed\(\)/)
assert.match(side, /acceptedButtons: Qt\.MiddleButton\s*onClicked: root\.dismissed\(\)/)
assert.match(side, /property: "topRightRadius"; value: Config\.dp\(20\)/)
assert.match(side, /property: "border\.width"; value: 0/)
assert.doesNotMatch(side, /searchSubmitted|settingsRequested|statusActive/)
const act = rd("../../bar/SidebarActivator.qml")
assert.match(act, /implicitWidth: 1/)
assert.match(act, /left: true; top: true; bottom: true/)
assert.match(act, /interval: 120$/m)
assert.match(act, /WlrLayershell\.layer: WlrLayer\.Top/)
assert.match(act, /onHoveredChanged: hovered \? dwell\.restart\(\) : dwell\.stop\(\)/, "leaving the edge cancels the dwell")
assert.match(act, /margins\.top: Config\.barWidth$/m, "clears the top strip")
assert.match(act, /margins\.bottom: Config\.bottomBarHeight$/m, "clears the bottom bar")
assert.match(act, /visible: Settings\.sidebarEdgeHover && root\.enabledByState/)
assert.match(act, /exclusionMode: ExclusionMode\.Ignore/)
const sh = rd("../../shell.qml")
const actInst = sh.slice(sh.indexOf("SidebarActivator {"), sh.indexOf("\n  }\n", sh.indexOf("SidebarActivator {")))
assert.ok(actInst.length > 0, "SidebarActivator instance")
assert.match(actInst, /enabledByState: !lockScreen\.locked/)
assert.match(actInst, /onActivated: if \(bar\.openPopup !== "sidebar" && Date\.now\(\) - shell\.sidebarClosedAt >= 300\)\s*shell\.openSidebarPage\(sidebar\.currentPage\)/,
  "hover never toggles an open sidebar closed, nor reopens one closed under 300 ms ago")
const sideInst = sh.slice(sh.indexOf("Sidebar {\n    id: sidebar"), sh.indexOf("SidebarActivator {"))
assert.match(sideInst, /onVisibleChanged: if \(!visible\) shell\.sidebarClosedAt = Date\.now\(\)/, "close time recorded")
assert.match(sh, /property real sidebarClosedAt: 0/)
assert.doesNotMatch(sh, /function sidebarSearch\(/)
assert.doesNotMatch(sh, /onSearchSubmitted/)
assert.match(sh, /function openLauncherWith\(query\)/, "kept per spec")
const content = rd("../../bar/sidebar/SidebarContent.qml")
assert.match(content, /readonly property int pageCount: 3/)
assert.match(content, /Qt\.Key_PageUp/)
for (const gone of ["SearchField", "StatsCard", "DashboardPage", "LevelBars", "statusActive", "dashboardActive", "searchSubmitted"])
  assert.doesNotMatch(content, new RegExp(gone), gone + " removed")
console.log("sidebar wiring: ok")
