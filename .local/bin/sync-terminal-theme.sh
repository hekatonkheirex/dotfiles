#!/bin/bash
# Syncs kitty, starship, fzf and niri window decorations to the current
# light/dark mode + colorscheme (matugen | claude) and Quickshell UI style. Called from
# sync-theme-mode.sh (mode changes) and Quickshell style/color changes. Safe to
# call with no args: re-reads current state and re-applies.
set -u

MODE="${1:-}"
SCHEME="${2:-}"
UI_STYLE="${3:-}"

QS_SCHEME_FILE="$HOME/.config/quickshell/colorscheme"
[ -z "$SCHEME" ] && SCHEME=$(cat "$QS_SCHEME_FILE" 2>/dev/null || echo matugen)
[ "$SCHEME" != "claude" ] && [ "$SCHEME" != "matugen" ] && SCHEME=matugen

if [ -z "$UI_STYLE" ]; then
  UI_STYLE=$(jq -r '.themeStyle // "material3"' "$HOME/.config/quickshell/settings.json" 2>/dev/null || echo material3)
fi
[ "$UI_STYLE" != "neo-brutalism" ] && [ "$UI_STYLE" != "nothing" ] && UI_STYLE=material3

if [ -z "$MODE" ] || [ "$MODE" = "auto" ]; then
  MODE=$("$HOME/.local/bin/auto-detect-theme.sh" 2>/dev/null)
  [ "$MODE" != "light" ] && [ "$MODE" != "dark" ] && MODE=dark
fi

# The UI style owns the terminal palette when it has a distinct identity.
# Material 3 keeps the selected terminal colorscheme, Nothing is fixed, and
# Neo Brutalism follows the wallpaper-derived Matugen roles.
KITTY_THEME_NAME="$SCHEME-$MODE.conf"
STARSHIP_THEME_NAME="$SCHEME-$MODE.toml"
NEO_TERMINAL_GENERATOR="$HOME/.config/quickshell/scripts/generate-neo-kitty-theme.sh"
if [ "$UI_STYLE" = "nothing" ]; then
  KITTY_THEME_NAME="nothing-$MODE.conf"
  STARSHIP_THEME_NAME="nothing-$MODE.toml"
elif [ "$UI_STYLE" = "neo-brutalism" ]; then
  KITTY_THEME_NAME="neo-brutalism-matugen-$MODE.conf"
  STARSHIP_THEME_NAME="neo-brutalism-matugen-$MODE.toml"
fi
KITTY_CONF="$HOME/.config/kitty/$KITTY_THEME_NAME"
STARSHIP_CONF="$HOME/.config/starship/$STARSHIP_THEME_NAME"

{
  echo "=== $(date) sync-terminal-theme MODE=$MODE SCHEME=$SCHEME UI_STYLE=$UI_STYLE KITTY=$KITTY_THEME_NAME STARSHIP=$STARSHIP_THEME_NAME ==="

  if [ "$UI_STYLE" = "neo-brutalism" ] && [ -x "$NEO_TERMINAL_GENERATOR" ]; then
    for kitty_mode in light dark; do
      "$NEO_TERMINAL_GENERATOR" "$kitty_mode" \
        || echo "Neo Brutalism Kitty/Starship $kitty_mode generation failed; keeping the previous themes."
    done
  fi

  if [ ! -f "$KITTY_CONF" ]; then
    echo "Kitty theme not found: $KITTY_CONF; falling back to $SCHEME-$MODE.conf"
    KITTY_THEME_NAME="$SCHEME-$MODE.conf"
    KITTY_CONF="$HOME/.config/kitty/$KITTY_THEME_NAME"
  fi

  if [ ! -f "$STARSHIP_CONF" ]; then
    echo "Starship theme not found: $STARSHIP_CONF; falling back to $SCHEME-$MODE.toml"
    STARSHIP_THEME_NAME="$SCHEME-$MODE.toml"
    STARSHIP_CONF="$HOME/.config/starship/$STARSHIP_THEME_NAME"
  fi

  # Kitty: swap the include indirection, then live-reload via SIGUSR1
  ln -sf "$KITTY_THEME_NAME" "$HOME/.config/kitty/theme.conf"
  killall -SIGUSR1 kitty 2>/dev/null

  # Starship + fzf: both read config from env vars, so regenerate a single
  # sourced file. New shells pick it up automatically; existing shells need
  # `source ~/.config/theme-env.sh` (starship also re-reads STARSHIP_CONFIG
  # live on every prompt, so it updates immediately in shells that re-source).
  col() { grep -E "^color${1}[[:space:]]" "$KITTY_CONF" | awk '{print $2}'; }
  FG=$(grep -E "^foreground[[:space:]]" "$KITTY_CONF" | awk '{print $2}')

  {
    echo "# Generated by sync-terminal-theme.sh — do not edit directly"
    echo "export STARSHIP_CONFIG=\"$STARSHIP_CONF\""
    cat "$HOME/.config/fzf/$SCHEME-$MODE.sh"

    # zsh-syntax-highlighting styles, derived from this scheme/mode's own
    # kitty ANSI colors — same colors already rendered on this exact
    # background, so contrast is correct by construction (avoids color0/8,
    # which are near-bg/outline tones with poor contrast in some schemes).
    echo "ZSH_HIGHLIGHT_HIGHLIGHTERS=(main cursor)"
    echo "typeset -gA ZSH_HIGHLIGHT_STYLES"
    echo "ZSH_HIGHLIGHT_STYLES[comment]='fg=$(col 7)'"
    for s in alias suffix-alias global-alias function command builtin reserved-word hashed-command; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 2)'"
    done
    echo "ZSH_HIGHLIGHT_STYLES[precommand]='fg=$(col 2),italic'"
    echo "ZSH_HIGHLIGHT_STYLES[autodirectory]='fg=$(col 3),italic'"
    for s in single-hyphen-option double-hyphen-option; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 3)'"
    done
    for s in back-quoted-argument history-expansion; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 5)'"
    done
    for s in commandseparator back-quoted-argument-delimiter back-double-quoted-argument back-dollar-quoted-argument \
             single-quoted-argument-unclosed double-quoted-argument-unclosed unknown-token back-quoted-argument-unclosed; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 1)'"
    done
    for s in command-substitution-quoted command-substitution-delimiter-quoted single-quoted-argument double-quoted-argument rc-quote; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 6)'"
    done
    for s in command-substitution-delimiter command-substitution-delimiter-unquoted process-substitution-delimiter globbing; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 4)'"
    done
    for s in path path_prefix; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 4),underline'"
    done
    for s in path_pathseparator path_prefix_pathseparator; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$(col 1),underline'"
    done
    for s in dollar-quoted-argument dollar-double-quoted-argument assign named-fd numeric-fd redirection arg0 default cursor; do
      echo "ZSH_HIGHLIGHT_STYLES[$s]='fg=$FG'"
    done
  } > "$HOME/.config/theme-env.sh"

  echo "kitty theme.conf -> $KITTY_THEME_NAME"
  echo "theme-env.sh -> STARSHIP_CONFIG=$STARSHIP_THEME_NAME, FZF from $SCHEME-$MODE.sh"
  echo "open shells will pick this up on their next prompt (mtime-checked precmd hook in .zshrc)"

  # Niri focus-ring/window-border colors and style-specific decoration overrides
  if [ "$SCHEME" = "claude" ]; then
    # Claude palette (matches config/Colors.qml cl_l_/cl_d_ primary + outline)
    if [ "$MODE" = "light" ]; then
      primary="#D97757"; outline="#898781"; on_surface="${FG:-#24191b}"; shadow="#000000"
    else
      primary="#DF8D72"; outline="#8F8A8A"; on_surface="${FG:-#f3dde0}"; shadow="${FG:-#000000}"
    fi
  else
    cache_file="$HOME/.cache/matugen/current_palette.json"
    if [ -f "$cache_file" ] && command -v jq &>/dev/null; then
      primary=$(jq -r ".\"scheme-expressive\".$MODE.primary" "$cache_file")
      outline=$(jq -r ".\"scheme-expressive\".$MODE.outline" "$cache_file")
      on_surface=$(jq -r ".\"scheme-expressive\".$MODE.on_surface" "$cache_file")
      shadow=$(jq -r ".\"scheme-expressive\".$MODE.shadow" "$cache_file")
    fi
  fi

  # Nothing is intentionally independent of the wallpaper-derived Matugen
  # palette. Keep Niri's window decorations on the same fixed neutral/red
  # roles as Quickshell's config/Colors.qml, including first boot/cache misses.
  if [ "$UI_STYLE" = "nothing" ]; then
    if [ "$MODE" = "light" ]; then
      primary="#d71920"
      outline="#858585"
      on_surface="#1a1a1a"
    else
      primary="#d71920"
      outline="#888884"
      on_surface="#f2f2f0"
    fi
    shadow="#000000"
  fi

  if [ -n "${primary:-}" ] && [ "$primary" != "null" ]; then
    if [ -z "${on_surface:-}" ] || [ "$on_surface" = "null" ]; then
      on_surface="${FG:-$outline}"
    fi
    if [ -z "${shadow:-}" ] || [ "$shadow" = "null" ]; then
      shadow="#000000"
    fi

    if [ "$UI_STYLE" = "neo-brutalism" ]; then
      focus_width=4
      focus_active="$on_surface"
      focus_inactive="$outline"
      niri_corner_radius=8
      neo_gap=18
      neo_shadow_offset=10
      layout_gaps="gaps $neo_gap"
      if [ "$MODE" = "dark" ]; then
        shadow_color="$on_surface"
      else
        shadow_color="$shadow"
      fi
    elif [ "$UI_STYLE" = "nothing" ]; then
      focus_width=1
      focus_active="$on_surface"
      focus_inactive="$outline"
      niri_corner_radius=20
      layout_gaps=""
    else
      focus_width=2
      focus_active="$primary"
      focus_inactive="$outline"
      niri_corner_radius=16
      layout_gaps=""
    fi

    mkdir -p "$HOME/.config/niri"
    colors_file="$HOME/.config/niri/colors.kdl"
    colors_tmp="$colors_file.tmp.$$"
    cat <<EOF > "$colors_tmp"
// Generated dynamically by sync-terminal-theme.sh
layout {
    $layout_gaps
    focus-ring {
        width $focus_width
        active-color "$focus_active"
        inactive-color "$focus_inactive"
    }
    border {
        off
        width $focus_width
        active-color "$focus_active"
        inactive-color "$focus_inactive"
        urgent-color "$primary"
    }
EOF
    if [ "$UI_STYLE" = "neo-brutalism" ]; then
      cat <<EOF >> "$colors_tmp"
    shadow {
        softness 0
        spread 0
        offset x=$neo_shadow_offset y=$neo_shadow_offset
        draw-behind-window true
        color "$shadow_color"
    }
EOF
    elif [ "$UI_STYLE" = "nothing" ]; then
      cat <<EOF >> "$colors_tmp"
    shadow {
        off
    }
EOF
    fi
cat <<EOF >> "$colors_tmp"
}
EOF
    if [ "$UI_STYLE" = "nothing" ]; then
      cat <<EOF >> "$colors_tmp"
window-rule {
    background-effect {
        blur false
    }
}
layer-rule {
    background-effect {
        blur false
    }
}
animations {
    workspace-switch {
        duration-ms 250
        curve "ease-out-quad"
    }
    window-open {
        duration-ms 200
        curve "ease-out-quad"
    }
    window-close {
        duration-ms 120
        curve "ease-out-quad"
    }
    horizontal-view-movement {
        duration-ms 150
        curve "ease-out-quad"
    }
    window-movement {
        duration-ms 150
        curve "ease-out-quad"
    }
    window-resize {
        duration-ms 150
        curve "ease-out-quad"
    }
    config-notification-open-close {
        duration-ms 150
        curve "ease-out-quad"
    }
    screenshot-ui-open {
        duration-ms 150
        curve "ease-out-quad"
    }
    overview-open-close {
        duration-ms 250
        curve "ease-out-quad"
    }
}
EOF
    fi
cat <<EOF >> "$colors_tmp"
window-rule {
    geometry-corner-radius $niri_corner_radius
    clip-to-geometry true
}
EOF
    mv -f "$colors_tmp" "$colors_file"
    echo "niri colors.kdl -> style=$UI_STYLE gaps=${neo_gap:-default} width=$focus_width radius=$niri_corner_radius active=$focus_active inactive=$focus_inactive shadow=${shadow_color:-default} offset=${neo_shadow_offset:-default}"

    # Niri does not need a session restart for included config changes. Reload
    # the live config so changing the UI style updates the focused ring now.
    if command -v niri &>/dev/null; then
      niri msg action load-config-file >/dev/null 2>&1 || true
    fi
  fi
} >> /tmp/sync-terminal-theme.log 2>&1
